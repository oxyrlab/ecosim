/**
 * Generates `docs/catalog/*.md` from the live registries and default config (`npm run docs:catalog`).
 * Never edit files under `docs/catalog/` by hand.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { shapeRegistry } from '@appearance/shapes';
import { actuatorRegistry, organRegistry, sensorRegistry } from '@body/index';
import { brainModuleRegistry } from '@brain/index';
import { HORMONE_SPECS, PORT_BUNDLES } from '@bus/index';
import { DEFAULT_RULE_CONFIG } from '@config/rules.default';
import '@rules/defs';
import { ruleRegistry } from '@rules/define-rule';
import { speciesRegistry, type SpeciesBlueprint } from '@species/index';
import { spineRegistry } from '@spine/index';

const root = resolve(import.meta.dirname, '..');
const catalogDir = join(root, 'docs', 'catalog');
mkdirSync(join(catalogDir, 'species'), { recursive: true });

const AUTO_HEADER = '<!-- Auto-generated by scripts/gen-catalog.ts — do not edit by hand. -->\n\n';

function generateRulesCatalog(): string {
  const rows = ruleRegistry.list().map((rule) => {
    const defaultEntry = DEFAULT_RULE_CONFIG[rule.id];
    const severity = defaultEntry?.severity ?? rule.defaultSeverity;
    const defaultParams =
      defaultEntry?.params !== undefined ? `\`${JSON.stringify(defaultEntry.params)}\`` : '—';
    return `| \`${rule.id}\` | ${rule.scope} | ${rule.category} | ${severity} | ${defaultParams} | ${rule.rationale} |`;
  });

  return [
    `${AUTO_HEADER}# Constraint Rules Catalog`,
    '',
    '| Id | Scope | Category | Default Severity | Default Params | Rationale |',
    '|---|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

function generateShapesCatalog(): string {
  const rows = shapeRegistry.list().map((s) => `| \`${s.id}\` | ${s.description} |`);
  return [
    `${AUTO_HEADER}# Shapes Catalog`,
    '',
    '| Id | Description |',
    '|---|---|',
    ...rows,
    '',
  ].join('\n');
}

function generateOrgansCatalog(): string {
  const rows = organRegistry
    .list()
    .map(
      (o) =>
        `| \`${o.id}\` | \`${o.defaultShape.type}\` | ${o.sensorSlots} | ${o.actuatorSlot ? 'yes' : 'no'} | ${o.massDensity} | ${o.description} |`,
    );
  return [
    `${AUTO_HEADER}# Organs Catalog`,
    '',
    '| Id | Default Shape | Sensor Slots | Actuator Slot | Mass Density (kg/m²) | Description |',
    '|---|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

function generateSensorsCatalog(): string {
  const rows = sensorRegistry
    .list()
    .map((s) => `| \`${s.id}\` | ${s.sampleRateHz ?? 'default'} Hz | ${s.description} |`);
  return [
    `${AUTO_HEADER}# Sensors Catalog`,
    '',
    '| Id | Sample Rate | Description |',
    '|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

function generateActuatorsCatalog(): string {
  const rows = actuatorRegistry.list().map((a) => `| \`${a.id}\` | ${a.description} |`);
  return [
    `${AUTO_HEADER}# Actuators Catalog`,
    '',
    '| Id | Description |',
    '|---|---|',
    ...rows,
    '',
  ].join('\n');
}

function generateBrainAndSpinesCatalog(): string {
  const modules = brainModuleRegistry.list();
  const spines = spineRegistry.list();

  const moduleSection =
    modules.length === 0
      ? 'No shared brain modules registered yet (added in Phase 5).\n'
      : [
          '| Id | Kind | Description |',
          '|---|---|---|',
          ...modules.map((m) => `| \`${m.id}\` | ${m.kind} | ${m.description} |`),
          '',
        ].join('\n');

  const spineSection = [
    '| Id | Description |',
    '|---|---|',
    ...spines.map((s) => `| \`${s.id}\` | ${s.description} |`),
    '',
  ].join('\n');

  return `${AUTO_HEADER}# Brain Modules & Spines Catalog\n\n## Brain Modules\n\n${moduleSection}\n## Spines\n\n${spineSection}`;
}

function generateChannelsCatalog(): string {
  const hormoneRows = Object.values(HORMONE_SPECS).map(
    (h) =>
      `| \`${h.id}\` | \`[${h.range[0]}, ${h.range[1]}]\` | \`${h.merge}\` | ${h.description} |`,
  );
  const bundleRows = Object.entries(PORT_BUNDLES).map(
    ([name, ports]) =>
      `| \`${name}\` | ${Object.keys(ports)
        .map((p) => `\`${p}\``)
        .join(', ')} |`,
  );

  return [
    `${AUTO_HEADER}# Signal Bundles & Broadcast Hormone Channels`,
    '',
    '## Broadcast Hormones',
    '',
    '| Hormone | Range | Merge Policy | Description |',
    '|---|---|---|---|',
    ...hormoneRows,
    '',
    '## Port Bundles',
    '',
    '| Bundle | Ports |',
    '|---|---|',
    ...bundleRows,
    '',
  ].join('\n');
}

function generateSpeciesDoc(sp: SpeciesBlueprint): string {
  if (sp.kingdom === 'plant') {
    return [
      `${AUTO_HEADER}# ${sp.name} (\`${sp.id}\`)`,
      '',
      `- **Kingdom:** \`plant\``,
      `- **Tags:** ${sp.tags.map((t) => `\`${t}\``).join(', ')}`,
      `- **Description:** ${sp.description}`,
      '',
      '| Property | Value |',
      '|---|---|',
      `| Adult Radius | ${sp.plantSpec.adultRadius} m |`,
      `| Max Energy | ${sp.plantSpec.maxEnergy} EU |`,
      `| Photosynthesis Rate | ${sp.plantSpec.photosynthesisRatePerArea} EU/(m²·s) |`,
      `| Pollination Radius | ${sp.plantSpec.pollinationRadiusMeters} m |`,
      `| Fruit Energy (Flesh + Seed) | ${sp.plantSpec.fruitFleshEnergy} + ${sp.plantSpec.seedEnergy} EU |`,
      '',
    ].join('\n');
  }

  return [
    `${AUTO_HEADER}# ${sp.name} (\`${sp.id}\`)`,
    '',
    `- **Kingdom:** \`animal\``,
    `- **Tags:** ${sp.tags.map((t) => `\`${t}\``).join(', ')}`,
    `- **Description:** ${sp.description}`,
    `- **Spine:** \`${sp.spine.spine}\``,
    `- **Brain Modules:** ${sp.brain.modules.map((m) => `\`${m.instanceId}\` (\`${m.module}\`)`).join(', ')}`,
    `- **Diet:** ${sp.diet.edibleTags.map((t) => `\`${t}\``).join(', ')} (assimilation \`${sp.diet.assimilationEfficiency}\`)`,
    '',
  ].join('\n');
}

function generateSpeciesIndex(): string {
  const rows = speciesRegistry
    .list()
    .map(
      (s) =>
        `| [\`${s.id}\`](${s.id}.md) | ${s.name} | \`${s.kingdom}\` | ${s.tags.map((t) => `\`${t}\``).join(', ')} | ${s.description} |`,
    );
  return [
    `${AUTO_HEADER}# Species Catalog`,
    '',
    '| Id | Name | Kingdom | Tags | Description |',
    '|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

const files: Record<string, string> = {
  'rules.md': generateRulesCatalog(),
  'shapes.md': generateShapesCatalog(),
  'organs.md': generateOrgansCatalog(),
  'sensors.md': generateSensorsCatalog(),
  'actuators.md': generateActuatorsCatalog(),
  'brain-modules.md': generateBrainAndSpinesCatalog(),
  'channels.md': generateChannelsCatalog(),
  'species/README.md': generateSpeciesIndex(),
};

for (const sp of speciesRegistry.list()) {
  files[`species/${sp.id}.md`] = generateSpeciesDoc(sp);
}

for (const [filename, content] of Object.entries(files)) {
  writeFileSync(join(catalogDir, filename), content, 'utf8');
}

console.log(
  `docs:catalog generated ${Object.keys(files).length} files (${shapeRegistry.size} shapes, ${ruleRegistry.size} rules, ${organRegistry.size} organs, ${sensorRegistry.size} sensors, ${actuatorRegistry.size} actuators, ${brainModuleRegistry.size} brain modules, ${spineRegistry.size} spines, ${speciesRegistry.size} species).`,
);
